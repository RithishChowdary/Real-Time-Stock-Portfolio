package com.major.stockportfolio.quantitative.report;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

import com.major.stockportfolio.quantitative.engine.AccountSnapshot;
import com.major.stockportfolio.quantitative.engine.BacktestResult;
import org.springframework.stereotype.Component;
import org.ta4j.core.BarSeries;
import org.ta4j.core.Position;
import org.ta4j.core.TradingRecord;

/**
 * Calculates trade statistics and portfolio-account metrics for a backtest.
 */
@Component
public class PerformanceMetricsCalculator {

    public static final double DEFAULT_INITIAL_CAPITAL = 100000.0;

    /**
     * Benchmark Indian annual risk-free rate assumption.
     */
    public static final double ANNUAL_RISK_FREE_RATE = 0.06;

    /**
     * Standard annual trading sessions in Indian equities (NSE/BSE).
     */
    public static final int TRADING_DAYS_PER_YEAR = 252;

    private static final int MINIMUM_SHARPE_RETURN_OBSERVATIONS = 4;

    /**
     * Calculates metrics from the account ledger generated by BacktestEngine.
     */
    public PerformanceMetrics calculate(BacktestResult backtestResult) {
        return calculate(backtestResult, DEFAULT_INITIAL_CAPITAL);
    }

    /**
     * Calculates account-level metrics from the actual per-bar equity snapshots,
     * and trade-level statistics from completed sized TA4J positions.
     */
    public PerformanceMetrics calculate(
            BacktestResult backtestResult,
            double initialCapital) {

        Objects.requireNonNull(backtestResult, "BacktestResult must not be null");
        validateInitialCapital(initialCapital);

        List<AccountSnapshot> snapshots = backtestResult.getAccountSnapshots();
        if (snapshots.isEmpty()) {
            throw new IllegalArgumentException(
                    "BacktestResult must contain at least one account snapshot"
            );
        }

        return calculateMetrics(
                backtestResult.getTradingRecord(),
                initialCapital,
                equityCurve(initialCapital, snapshots)
        );
    }

    /**
     * Backward-compatible entry point for callers that only have a trading
     * record. It reconstructs a mark-to-market equity curve from recorded
     * positions and bar closes; new backtest paths should pass BacktestResult.
     */
    public PerformanceMetrics calculate(
            BarSeries series,
            TradingRecord tradingRecord) {
        return calculate(series, tradingRecord, DEFAULT_INITIAL_CAPITAL);
    }

    /**
     * Backward-compatible adapter for callers that do not yet provide the
     * capital-aware BacktestResult.
     */
    public PerformanceMetrics calculate(
            BarSeries series,
            TradingRecord tradingRecord,
            double initialCapital) {

        Objects.requireNonNull(series, "BarSeries must not be null");
        Objects.requireNonNull(tradingRecord, "TradingRecord must not be null");
        if (series.isEmpty()) {
            throw new IllegalArgumentException(
                    "BarSeries must contain at least one bar"
            );
        }
        if (!Double.isFinite(initialCapital)) {
            throw new IllegalArgumentException(
                    "Initial capital must be finite"
            );
        }

        double validInitialCapital = Math.max(0.0, initialCapital);
        return calculateMetrics(
                tradingRecord,
                validInitialCapital,
                legacyEquityCurve(series, tradingRecord, validInitialCapital)
        );
    }

    private PerformanceMetrics calculateMetrics(
            TradingRecord tradingRecord,
            double initialCapital,
            List<Double> equityCurve) {

        List<Position> completedPositions = tradingRecord.getPositions().stream()
                .filter(Objects::nonNull)
                .filter(position -> position.getEntry() != null && position.getExit() != null)
                .toList();

        int totalTrades = completedPositions.size();
        int winningTrades = 0;
        int losingTrades = 0;
        double totalProfit = 0.0;
        double totalLoss = 0.0;

        for (Position position : completedPositions) {
            double profitLoss = position.getProfit().doubleValue();
            if (profitLoss > 0.0) {
                totalProfit += profitLoss;
                winningTrades++;
            } else if (profitLoss < 0.0) {
                totalLoss += Math.abs(profitLoss);
                losingTrades++;
            }
        }

        double finalPortfolioValue = round(equityCurve.get(equityCurve.size() - 1));
        double totalEarnings = round(finalPortfolioValue - initialCapital);
        double winRate = totalTrades == 0
                ? 0.0
                : round((double) winningTrades / totalTrades * 100.0);
        double completedTradeEarnings = totalProfit - totalLoss;
        double averageProfit = totalTrades == 0
                ? 0.0
                : round(completedTradeEarnings / totalTrades);
        double expectancy = averageProfit;
        double averageWinningTrade = winningTrades == 0
                ? 0.0
                : round(totalProfit / winningTrades);
        double averageLosingTrade = losingTrades == 0
                ? 0.0
                : round(totalLoss / losingTrades);

        Double riskRewardRatio =
                losingTrades > 0 && averageLosingTrade > 0.0 && averageWinningTrade > 0.0
                        ? round(averageWinningTrade / averageLosingTrade)
                        : null;

        Double profitFactor;
        if (totalLoss == 0.0) {
            profitFactor = totalProfit > 0.0 ? null : 0.0;
        } else {
            profitFactor = round(totalProfit / totalLoss);
        }

        double returnOnInvestment = initialCapital > 0.0
                ? round(totalEarnings / initialCapital * 100.0)
                : 0.0;
        double maximumDrawdown = calculateMaximumDrawdown(equityCurve);
        Double sharpeRatio = calculateSharpeRatio(equityCurve.subList(1, equityCurve.size()));

        return new PerformanceMetrics(
                totalTrades,
                winningTrades,
                losingTrades,
                winRate,
                round(totalProfit),
                round(totalLoss),
                totalEarnings,
                averageProfit,
                maximumDrawdown,
                profitFactor,
                initialCapital,
                finalPortfolioValue,
                returnOnInvestment,
                expectancy,
                averageWinningTrade,
                averageLosingTrade,
                riskRewardRatio,
                sharpeRatio
        );
    }

    private List<Double> equityCurve(
            double initialCapital,
            List<AccountSnapshot> snapshots) {
        List<Double> equityValues = new ArrayList<>(snapshots.size() + 1);
        equityValues.add(initialCapital);

        for (AccountSnapshot snapshot : snapshots) {
            Objects.requireNonNull(snapshot, "Account snapshot must not be null");
            double equity = snapshot.getEquity();
            if (!Double.isFinite(equity)) {
                throw new IllegalArgumentException(
                        "Account equity must be finite at bar " + snapshot.getBarIndex()
                );
            }
            equityValues.add(equity);
        }
        return equityValues;
    }

    /**
     * Reconstructs an equity curve only for source-compatible legacy callers.
     * Capital-aware engine paths use AccountSnapshot values directly.
     */
    private List<Double> legacyEquityCurve(
            BarSeries series,
            TradingRecord tradingRecord,
            double initialCapital) {

        List<Position> positions = new ArrayList<>();
        for (Position position : tradingRecord.getPositions()) {
            if (position != null && position.getEntry() != null) {
                positions.add(position);
            }
        }

        Position currentPosition = tradingRecord.getCurrentPosition();
        if (currentPosition != null
                && currentPosition.isOpened()
                && !positions.contains(currentPosition)) {
            positions.add(currentPosition);
        }

        List<Double> equityValues = new ArrayList<>(series.getBarCount() + 1);
        equityValues.add(initialCapital);
        for (int index = series.getBeginIndex(); index <= series.getEndIndex(); index++) {
            double realizedPnl = 0.0;
            double unrealizedPnl = 0.0;
            double closePrice = series.getBar(index).getClosePrice().doubleValue();

            for (Position position : positions) {
                int entryIndex = position.getEntry().getIndex();
                if (entryIndex > index) {
                    continue;
                }

                if (position.getExit() != null && position.getExit().getIndex() <= index) {
                    realizedPnl += position.getProfit().doubleValue();
                } else {
                    double entryPrice = position.getEntry().getPricePerAsset().doubleValue();
                    double quantity = position.getEntry().getAmount().doubleValue();
                    unrealizedPnl += (closePrice - entryPrice) * quantity;
                }
            }

            equityValues.add(initialCapital + realizedPnl + unrealizedPnl);
        }
        return equityValues;
    }

    private double calculateMaximumDrawdown(List<Double> equityCurve) {
        double peak = equityCurve.get(0);
        double maximumDrawdown = 0.0;

        for (double equity : equityCurve) {
            if (equity > peak) {
                peak = equity;
            }
            if (peak > 0.0) {
                double drawdown = (peak - equity) / peak * 100.0;
                maximumDrawdown = Math.max(maximumDrawdown, drawdown);
            }
        }
        return round(maximumDrawdown);
    }

    /**
     * Annualized Sharpe from consecutive AccountSnapshot equity returns:
     * (mean daily return - daily risk-free rate) / sample standard deviation
     * multiplied by sqrt(252).
     *
     * <p>The supplied values contain actual bar snapshots only; initial capital
     * is deliberately excluded from this daily-return series.</p>
     */
    private Double calculateSharpeRatio(List<Double> snapshotEquities) {
        List<Double> dailyReturns = new ArrayList<>(Math.max(0, snapshotEquities.size() - 1));
        for (int index = 1; index < snapshotEquities.size(); index++) {
            double previousEquity = snapshotEquities.get(index - 1);
            double currentEquity = snapshotEquities.get(index);
            if (previousEquity <= 0.0) {
                continue;
            }
            dailyReturns.add((currentEquity - previousEquity) / previousEquity);
        }

        if (dailyReturns.size() < MINIMUM_SHARPE_RETURN_OBSERVATIONS) {
            return null;
        }

        double meanReturn = dailyReturns.stream()
                .mapToDouble(Double::doubleValue)
                .average()
                .orElseThrow();

        double squaredDifferences = 0.0;
        for (double dailyReturn : dailyReturns) {
            double difference = dailyReturn - meanReturn;
            squaredDifferences += difference * difference;
        }

        double variance = squaredDifferences / (dailyReturns.size() - 1);
        double standardDeviation = Math.sqrt(variance);
        if (!Double.isFinite(standardDeviation) || standardDeviation <= 1e-12) {
            return null;
        }

        double dailyRiskFreeRate = ANNUAL_RISK_FREE_RATE / TRADING_DAYS_PER_YEAR;
        double annualizedSharpe =
                (meanReturn - dailyRiskFreeRate)
                        / standardDeviation
                        * Math.sqrt(TRADING_DAYS_PER_YEAR);
        if (!Double.isFinite(annualizedSharpe)) {
            return null;
        }
        return round(annualizedSharpe);
    }

    private void validateInitialCapital(double initialCapital) {
        if (!Double.isFinite(initialCapital) || initialCapital <= 0.0) {
            throw new IllegalArgumentException(
                    "Initial capital must be finite and greater than zero"
            );
        }
    }

    private static double round(double value) {
        return BigDecimal.valueOf(value)
                .setScale(2, RoundingMode.HALF_UP)
                .doubleValue();
    }
}
